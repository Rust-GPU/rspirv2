use super::preamble::*;
pub fn decode_dyn<R, F>(reader: &mut InstructionReader, f: F) -> Result<R, DecodeError>
where
    F: FnOnce(&dyn DynInst) -> R,
{
    Ok(match reader.opcode() {
        1u16 => f(&<Round as Inst>::decode(reader)?),
        2u16 => f(&<RoundEven as Inst>::decode(reader)?),
        3u16 => f(&<Trunc as Inst>::decode(reader)?),
        4u16 => f(&<FAbs as Inst>::decode(reader)?),
        5u16 => f(&<SAbs as Inst>::decode(reader)?),
        6u16 => f(&<FSign as Inst>::decode(reader)?),
        7u16 => f(&<SSign as Inst>::decode(reader)?),
        8u16 => f(&<Floor as Inst>::decode(reader)?),
        9u16 => f(&<Ceil as Inst>::decode(reader)?),
        10u16 => f(&<Fract as Inst>::decode(reader)?),
        11u16 => f(&<Radians as Inst>::decode(reader)?),
        12u16 => f(&<Degrees as Inst>::decode(reader)?),
        13u16 => f(&<Sin as Inst>::decode(reader)?),
        14u16 => f(&<Cos as Inst>::decode(reader)?),
        15u16 => f(&<Tan as Inst>::decode(reader)?),
        16u16 => f(&<Asin as Inst>::decode(reader)?),
        17u16 => f(&<Acos as Inst>::decode(reader)?),
        18u16 => f(&<Atan as Inst>::decode(reader)?),
        19u16 => f(&<Sinh as Inst>::decode(reader)?),
        20u16 => f(&<Cosh as Inst>::decode(reader)?),
        21u16 => f(&<Tanh as Inst>::decode(reader)?),
        22u16 => f(&<Asinh as Inst>::decode(reader)?),
        23u16 => f(&<Acosh as Inst>::decode(reader)?),
        24u16 => f(&<Atanh as Inst>::decode(reader)?),
        25u16 => f(&<Atan2 as Inst>::decode(reader)?),
        26u16 => f(&<Pow as Inst>::decode(reader)?),
        27u16 => f(&<Exp as Inst>::decode(reader)?),
        28u16 => f(&<Log as Inst>::decode(reader)?),
        29u16 => f(&<Exp2 as Inst>::decode(reader)?),
        30u16 => f(&<Log2 as Inst>::decode(reader)?),
        31u16 => f(&<Sqrt as Inst>::decode(reader)?),
        32u16 => f(&<InverseSqrt as Inst>::decode(reader)?),
        33u16 => f(&<Determinant as Inst>::decode(reader)?),
        34u16 => f(&<MatrixInverse as Inst>::decode(reader)?),
        35u16 => f(&<Modf as Inst>::decode(reader)?),
        36u16 => f(&<ModfStruct as Inst>::decode(reader)?),
        37u16 => f(&<FMin as Inst>::decode(reader)?),
        38u16 => f(&<UMin as Inst>::decode(reader)?),
        39u16 => f(&<SMin as Inst>::decode(reader)?),
        40u16 => f(&<FMax as Inst>::decode(reader)?),
        41u16 => f(&<UMax as Inst>::decode(reader)?),
        42u16 => f(&<SMax as Inst>::decode(reader)?),
        43u16 => f(&<FClamp as Inst>::decode(reader)?),
        44u16 => f(&<UClamp as Inst>::decode(reader)?),
        45u16 => f(&<SClamp as Inst>::decode(reader)?),
        46u16 => f(&<FMix as Inst>::decode(reader)?),
        47u16 => f(&<IMix as Inst>::decode(reader)?),
        48u16 => f(&<Step as Inst>::decode(reader)?),
        49u16 => f(&<SmoothStep as Inst>::decode(reader)?),
        50u16 => f(&<Fma as Inst>::decode(reader)?),
        51u16 => f(&<Frexp as Inst>::decode(reader)?),
        52u16 => f(&<FrexpStruct as Inst>::decode(reader)?),
        53u16 => f(&<Ldexp as Inst>::decode(reader)?),
        54u16 => f(&<PackSnorm4x8 as Inst>::decode(reader)?),
        55u16 => f(&<PackUnorm4x8 as Inst>::decode(reader)?),
        56u16 => f(&<PackSnorm2x16 as Inst>::decode(reader)?),
        57u16 => f(&<PackUnorm2x16 as Inst>::decode(reader)?),
        58u16 => f(&<PackHalf2x16 as Inst>::decode(reader)?),
        59u16 => f(&<PackDouble2x32 as Inst>::decode(reader)?),
        60u16 => f(&<UnpackSnorm2x16 as Inst>::decode(reader)?),
        61u16 => f(&<UnpackUnorm2x16 as Inst>::decode(reader)?),
        62u16 => f(&<UnpackHalf2x16 as Inst>::decode(reader)?),
        63u16 => f(&<UnpackSnorm4x8 as Inst>::decode(reader)?),
        64u16 => f(&<UnpackUnorm4x8 as Inst>::decode(reader)?),
        65u16 => f(&<UnpackDouble2x32 as Inst>::decode(reader)?),
        66u16 => f(&<Length as Inst>::decode(reader)?),
        67u16 => f(&<Distance as Inst>::decode(reader)?),
        68u16 => f(&<Cross as Inst>::decode(reader)?),
        69u16 => f(&<Normalize as Inst>::decode(reader)?),
        70u16 => f(&<FaceForward as Inst>::decode(reader)?),
        71u16 => f(&<Reflect as Inst>::decode(reader)?),
        72u16 => f(&<Refract as Inst>::decode(reader)?),
        73u16 => f(&<FindILsb as Inst>::decode(reader)?),
        74u16 => f(&<FindSMsb as Inst>::decode(reader)?),
        75u16 => f(&<FindUMsb as Inst>::decode(reader)?),
        76u16 => f(&<InterpolateAtCentroid as Inst>::decode(reader)?),
        77u16 => f(&<InterpolateAtSample as Inst>::decode(reader)?),
        78u16 => f(&<InterpolateAtOffset as Inst>::decode(reader)?),
        79u16 => f(&<NMin as Inst>::decode(reader)?),
        80u16 => f(&<NMax as Inst>::decode(reader)?),
        81u16 => f(&<NClamp as Inst>::decode(reader)?),
        opcode => return Err(DecodeError::UnknownOpCode { opcode }),
    })
}
